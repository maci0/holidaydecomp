#!/usr/bin/env python3
"""`docs/status.md`: where the reconstruction stands, every number measured.

Round 100's answer to "what is known, what is left". Nothing here is typed by
hand: the score comes from `rebrew.formats.ne_analysis`, the coverage from the
generated documents' own data, the round count from `notes.txt`. Regenerate with
`python3 tools/gen_status.py`, check with `--check` (the suite does).
"""

from __future__ import annotations

import argparse
import csv
import io
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import decompile  # noqa: E402
import gen_globals  # noqa: E402
import gen_strings  # noqa: E402
from rebrew.formats import ne_analysis  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "status.md"
NOTES = ROOT / "notes.txt"


def unit_names() -> dict[int, str]:
    """segment -> `NAME.PAS`, from the generated unit dossiers."""
    found: dict[int, str] = {}
    for match in re.finditer(
        r"## `([A-Z0-9_.]+)` \(segment (\d+)\)",
        (ROOT / "docs" / "units.md").read_text(encoding="utf-8"),
    ):
        found[int(match.group(2))] = match.group(1)
    return found


def render() -> str:
    image = decompile.Image(decompile.ORIGINAL)
    lines = [
        "# Where the reconstruction stands",
        "",
        "Generated by `tools/gen_status.py` from the binary and the generated",
        "documents themselves, so no number here can drift from the thing it",
        "describes.",
        "",
        "## The rebuild",
        "",
    ]
    rebuilt = ROOT / "bin" / "main" / "HOLIDAY.EXE"
    if rebuilt.is_file():
        original = ne_analysis.NeImage(decompile.ORIGINAL)
        built = ne_analysis.NeImage(rebuilt)
        blocks, total = ne_analysis.byte_score(original, built, 16)
        lines += [
            f"* **{blocks} of {total} original bytes reproduced in 16-byte windows "
            f"= {100 * blocks / total:.2f} %**.",
            f"* the rebuild is {len(built.data)} bytes against the original's {total}.",
        ]
    else:
        lines.append("* not built yet (`./build.sh`)")
    lines += ["", "## The classes this run has closed", ""]
    caches = {
        "build/leaf-census.json": "leaf procedures classified (`calls == []`)",
        "build/pair-kinds.json": "same-size near-twin pairs, by kind",
        "build/coordinator-census.json": "procedures counted by how far they reach",
        "build/loop-census.json": "procedures that contain a loop",
        "build/masked-pairs.json": "pairs, with relocation fields masked",
        "build/stride-census.json": "every `imul` stride in the program",
        "build/cbe-lengths.json": "the library copier's length argument",
        "build/vtable-slots.json": "the virtual-method slots the program calls",
        "build/fan-density.json": "cross-unit call density per procedure",
        "build/repetition-census.json": "repetitions, looped or written out",
        "build/string-census.json": "the program's string calls",
        "build/small-families.json": "size families below the 50-byte floor",
    }
    for name, what in caches.items():
        path = ROOT / name
        if not path.is_file():
            continue
        lines.append(f"* `{name}` — {what}.")
    lines += ["", "## Where the reversal stands, unit by unit", ""]
    worklist = ROOT / "docs" / "worklist.csv"
    if worklist.is_file():
        import csv as _csv

        rows = list(_csv.DictReader(worklist.read_text(encoding="utf-8").splitlines()))
        per_unit: dict[str, list] = {}
        for row in rows:
            per_unit.setdefault(row["segment"], []).append(row)
        names = unit_names()
        # Computed, not typed: this sentence carried hand-typed counts until round
        # 436, when three of the four were stale (UEBERMAP read "11 of 103" and was
        # 38 of 103). Every number here is derived from the rows below it.
        ratios = {
            segment: (sum(1 for row in unit_rows if row["documented"] == "yes"),
                      len(unit_rows))
            for segment, unit_rows in per_unit.items()
        }
        def describe(segment: str) -> str:
            discussed, total = ratios[segment]
            return f"**{segment} (`{names.get(int(segment), '?')}`, {discussed} of {total})**"

        thinnest = sorted(ratios, key=lambda s: (ratios[s][0] / ratios[s][1], s))[:2]
        thickest = sorted(ratios, key=lambda s: (-ratios[s][0] / ratios[s][1],
                                                 -ratios[s][1], s))[:2]
        biggest = max(ratios, key=lambda s: (ratios[s][1], -int(s)))
        lines += [
            "The worklist marks a procedure as discussed when a document names its",
            "address, so this is measured rather than judged. The thinnest units by",
            f"ratio are {describe(thinnest[0])} and {describe(thinnest[1])}, and",
            f"{biggest} holds the most procedures of any unit in the program; the",
            f"thickest are {describe(thickest[0])} and {describe(thickest[1])}. A later",
            "round reads the thin rows first.",
            "",
            "| unit | segment | discussed | procedures | bytes |",
            "| --- | ---: | ---: | ---: | ---: |",
        ]
        for segment, unit_rows in sorted(per_unit.items(), key=lambda kv: int(kv[0])):
            discussed = sum(1 for row in unit_rows if row["documented"] == "yes")
            total = len(unit_rows)
            size = sum(int(row["size"]) for row in unit_rows)
            lines.append(
                f"| `{names.get(int(segment), '?')}` | {segment} | {discussed} | {total} "
                f"| {size} |"
            )
        lines.append("")
    lines += ["", "## What the documents cover", ""]

    census, _dropped = decompile.datamap(image)
    immediate = decompile.immediate_refs(image)
    code = decompile.immediate_code_refs(image)
    literals = decompile.immediate_literal_refs(image)
    globals_named = len(gen_globals.NAMES)
    strings = gen_strings.literals(image)
    rows = list(
        csv.DictReader(io.StringIO((ROOT / "docs" / "worklist.csv").read_text()))
    )
    documented = sum(1 for row in rows if row["documented"] == "yes")

    lines += [
        "* segments: **25 program units**, each with a job in "
        "`docs/segment-map.md`, plus the VCL and the data segment.",
        f"* procedures: **{len(rows)}** in `docs/worklist.csv`, "
        f"**{documented}** named by a document.",
        f"* globals: **{len(census)}** reached by `[0xNNNN]`, **{len(immediate)}** "
        f"more passed as addresses, **{globals_named}** with a documented role.",
        f"* code-segment addresses: **{len(code)}**, of which "
        f"**{len(literals)}** are string constants.",
        f"* string literals: **{len(strings)}** distinct, one row each in "
        "`docs/strings.md`.",
        "",
        "## Documents",
        "",
        "| document | lines |",
        "| --- | ---: |",
    ]
    for path in sorted((ROOT / "docs").glob("*.md")):
        if path.name == DOC.name:
            continue  # listing itself would make the render depend on its own length
        lines.append(
            f"| [`{path.name}`]({path.name}) | {len(path.read_text(encoding='utf-8').splitlines())} |"
        )
    rounds = re.findall(r"^round (\d+)", NOTES.read_text(encoding="utf-8"), re.M)
    # Round numbers, not line count: appending to notes.txt makes the line count a
    # measurement of this run rather than of the image, and a document that drifts
    # every time a round is recorded is a document that gets regenerated instead of
    # read. This line moves when a *round* is added, which is the fact it states.
    lines += [
        "",
        "## The rounds",
        "",
        f"* **{max(int(r) for r in rounds)} rounds** recorded in `notes.txt`.",
        "* the score history, per measurement: 0.00 % (first link) -> 18.44 % "
        "(the pools unit) -> 19.00 % (the trailer matched) -> **"
        + (
            f"{100 * ne_analysis.byte_score(ne_analysis.NeImage(decompile.ORIGINAL), ne_analysis.NeImage(rebuilt), 16)[0] / len(ne_analysis.NeImage(decompile.ORIGINAL).data):.2f} %"
            if rebuilt.is_file()
            else "unbuilt"
        )
        + "** (the reach unit and its sweeps).",
        "",
        "## What is left",
        "",
        "* **the program units' bodies** — 400 KB of the original that no source "
        "exists for; a scaffold reproduces the declarations, not the code.",
        "* **the library's unreached code** — the segments are 36-68 % matched; "
        "the rest is API the game calls and the probes do not (yet).",
        "* **the data segment's variables** — 13 % matched; the rest is storage "
        "the original's units sized and filled.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate docs/status.md")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not DOC.is_file() or DOC.read_text(encoding="utf-8") != text:
            print("docs/status.md is stale; run python3 tools/gen_status.py")
            return 1
        print("docs/status.md is current")
        return 0
    DOC.write_text(text, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
