#!/usr/bin/env python3
"""Generate STATUS.md and status.json from tracked source and Rebrew metadata."""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path

import gen_tree
from rebrew.metadata.functions import load_metadata

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "status.json"
DOC = ROOT / "STATUS.md"


def source_paths() -> list[Path]:
    names = [f"{unit}.PAS" for _, unit, _, _ in gen_tree.generated_units()]
    return [ROOT / "src/main" / name for name in [*names, "HOLIDAY.DPR", "REACH.PAS"]]


def source_hash() -> str:
    digest = hashlib.sha256()
    paths = source_paths() + [ROOT / p for p in (
        "tools/gen_tree.py", "tools/gen_data.py", "tools/gen_pools.py",
        "tools/gen_tables.py", "tools/dfm_extract.py", "tools/dfm_pack.py",
        "templates/REACH.PAS", "build.sh", "rebrew-project.toml", "uv.lock",
    )]
    for path in sorted(paths):
        digest.update(path.relative_to(ROOT).as_posix().encode() + b"\0" + path.read_bytes())
    return digest.hexdigest()


def report(measure: bool = False) -> dict:
    fingerprint = source_hash()
    units = {f"src/main/{name}.PAS": Counter() for _, name, _, _ in gen_tree.generated_units()}
    totals = Counter()
    for (module, _), entry in load_metadata(ROOT).items():
        if module != "MAIN":
            continue
        file = entry.get("file")
        note = entry.get("note", "")
        state = "unbound"
        if file:
            state = "candidate" if note == "Source body: candidate; not a byte-match verdict." else "empty_stub"
            units[file][state] += 1
        totals[state] += 1
        if entry.get("status") in {"EXACT", "RELOC"}:
            totals[entry["status"].lower()] += 1
    measurement = None
    if JSON_PATH.exists():
        previous = json.loads(JSON_PATH.read_text())
        if previous.get("source_sha256") == fingerprint:
            measurement = previous.get("measurement")
    if measure:
        from rebrew.formats import ne_analysis
        original = ne_analysis.NeImage(ROOT / "original/holiday.exe")
        rebuilt = ne_analysis.NeImage(ROOT / "bin/main/HOLIDAY.EXE")
        covered, total, segments = ne_analysis.comparison_content(original, rebuilt, 16)
        measurement = {
            "metric": "whole-file matching-window union", "window": 16,
            "covered_bytes": covered, "reference_bytes": total,
            "same_offset_bytes": sum(a == b for a, b in zip(original.data, rebuilt.data)),
            "rebuilt_bytes": len(rebuilt.data), "raw_exact": original.data == rebuilt.data,
            "reference_sha256": hashlib.sha256(original.data).hexdigest(),
            "rebuilt_sha256": hashlib.sha256(rebuilt.data).hexdigest(),
            "segments": [{"index": index, "bytes": size, "covered_bytes": count}
                         for index, size, count in segments],
        }
    return {
        "target": "main", "source_sha256": fingerprint,
        "source_files": len(source_paths()), "procedures": dict(sorted(totals.items())),
        "units": [{"file": file, "candidate": counts["candidate"], "empty_stub": counts["empty_stub"]}
                  for file, counts in units.items()],
        "measurement": measurement,
    }


def render(data: dict) -> str:
    counts = data["procedures"]
    total = sum(counts.get(key, 0) for key in ("candidate", "empty_stub", "unbound"))
    lines = [
        "# Decompilation status", "", "Generated by `tools/gen_status.py`; update with `make status`.", "",
        f"The repository tracks **{data['source_files']} Pascal/project files** and **{total} native procedures**.", "",
        "| Source state | Procedures |", "| --- | ---: |",
        f"| Non-empty source candidates | {counts.get('candidate', 0)} |",
        f"| Empty scaffold stubs | {counts.get('empty_stub', 0)} |",
        f"| No source definition bound | {counts.get('unbound', 0)} |",
        f"| Recorded raw EXACT verdicts | {counts.get('exact', 0)} |",
        f"| Recorded relocation-masked RELOC verdicts | {counts.get('reloc', 0)} |", "",
        "Non-empty means code exists, not that it is complete, correct or byte-matched.",
        "Rebrew defaults unverified bindings to STUB; its source coverage includes empty stubs.",
        "Historical probe results have not been promoted into per-function verified verdicts.", "",
        "## Current build measurement", "",
    ]
    measurement = data["measurement"]
    if measurement:
        covered, size = measurement["covered_bytes"], measurement["reference_bytes"]
        lines += [
            f"**{covered:,}/{size:,} bytes ({100 * covered / size:.2f}%)** overlap in exact 16-byte windows.",
            f"Same-offset bytes: {measurement['same_offset_bytes']:,}/{size:,}. "
            f"Rebuild size: {measurement['rebuilt_bytes']:,} bytes. "
            f"Complete-file equality: **{'yes' if measurement['raw_exact'] else 'no'}**.", "",
            "This includes library code, data and resources; it is **not a percentage decompiled**.",
            "Matches can occur at different offsets. Source/input hashes and segment overlap are in [status.json](status.json).", "",
        ]
    else:
        lines += ["No build measurement for these sources. Build locally, then run `make status-measure`.", ""]
    lines += [
        "## By source unit", "", "| Unit | Non-empty candidates | Empty stubs |",
        "| --- | ---: | ---: |",
    ]
    for row in data["units"]:
        path = row["file"]
        lines.append(f"| [{Path(path).name}]({path}) | {row['candidate']} | {row['empty_stub']} |")
    lines += [
        "", "## Remaining work", "",
        "- Recover empty and unbound procedures; review incomplete candidate bodies and callees.",
        "- Verify native behavior and per-procedure bytes before recording matched verdicts.",
        "- Resolve original field types, object ownership, near/far calls and compiler layout differences.",
        "- Migrate reviewed global ownership into `rebrew-data.toml`; it currently has no verified data rows.",
        "", "Use `rebrew status --json` and `rebrew todo --json` for the managed function inventory.",
        "Native checks require your own reference and Delphi toolchain. Full gameplay parity is unverified.", "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--measure", action="store_true", help="measure the local reference and rebuilt images")
    args = parser.parse_args()
    data = report(args.measure)
    outputs = {JSON_PATH: json.dumps(data, indent=2) + "\n", DOC: render(data)}
    if args.check:
        stale = [p.name for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("Stale status tracker: " + ", ".join(stale) + "; run make status")
            return 1
        print("Decompilation status tracker current")
    else:
        for path, text in outputs.items():
            path.write_text(text)
        print("Updated STATUS.md and status.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
