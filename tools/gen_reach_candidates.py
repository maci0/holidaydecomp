#!/usr/bin/env python3
"""Turn a `.DCU`'s class members into sweep candidates.

`tools/dcu_symbols.py` reads the members; this writes the candidate lines for
the classes the reach unit has objects for, in the four forms a member can take
(read into an integer, read into a string, assign a number, call with no
arguments). Wrong guesses cost the sweep one compile each and are dropped, so the
generator can be generous.

    python3 tools/gen_reach_candidates.py --out tools/reach_candidates3.txt
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import dcu_symbols  # noqa: E402

LIB = (Path(__file__).resolve().parent.parent / "toolchain" / "recompile-toolchains"
       / "delphi" / "1.0-win16" / "source" / "DELPHI" / "LIB")

# class -> (unit, the reach unit's variable for it). The variables already exist
# in REACH.PAS; a class without one is skipped.
OBJECTS: dict[str, tuple[str, str]] = {
    "TForm": ("Forms", "gSweepForm"),
    "TScrollingWinControl": ("Forms", "gSweepForm"),
    "TScrollBox": ("Forms", "gSweepBox"),
    "TCanvas": ("Graphics", "gSweepCanvas"),
    "TPen": ("Graphics", "gSweepPen"),
    "TBrush": ("Graphics", "gSweepBrush"),
    "TFont": ("Graphics", "gSweepFont"),
    "TPicture": ("Graphics", "gSweepPicture"),
    "TIcon": ("Graphics", "gSweepIcon"),
    "TMetafile": ("Graphics", "gSweepMeta"),
    "TBitmap": ("Graphics", "gSweepBitmap"),
    "TGraphic": ("Graphics", "gSweepGraphic"),
    "TControl": ("Controls", "gSweepControl"),
    "TWinControl": ("Controls", "gSweepWin"),
    "TButton": ("Buttons", "gSweepButton"),
    "TButtonControl": ("Buttons", "gSweepButton"),
    "TMediaPlayer": ("MPlayer", "gSweepPlayer"),
    "TListBox": ("StdCtrls", "gSweepList"),
    "TComboBox": ("StdCtrls", "gSweepCombo"),
    "TEdit": ("StdCtrls", "gSweepEdit"),
    "TLabel": ("StdCtrls", "gSweepLabel"),
    "TCheckBox": ("StdCtrls", "gSweepCheck"),
    "TRadioButton": ("StdCtrls", "gSweepRadio"),
    "TGroupBox": ("StdCtrls", "gSweepGroup"),
    "TMemo": ("StdCtrls", "gSweepMemo"),
    "TScrollBar": ("StdCtrls", "gSweepScroll"),
    "TStringList": ("Classes", "gSweepStrings"),
    "TList": ("Classes", "gSweepList2"),
    "TStream": ("Classes", "gSweepStream"),
    "TComponent": ("Classes", "gSweepComponent"),
}

FORMS = (
    "n2 := {obj}.{member};",
    "s2 := {obj}.{member};",
)

# Private and protected members never compile from another unit; skipping them
# saves the sweep a compile each.
INTERNAL = ("F", "Get", "Set", "WM", "CM", "Do", "Create", "Destroy", "Update",
            "Changed", "Notification", "DefineProperties", "Is", "Can", "Calc",
            "Needs", "Assign", "Read", "Write", "Loaded", "Load", "Save",
            "Init", "Final", "Alloc", "Free", "New", "Dispose")


def is_public(member: str) -> bool:
    return not any(member.startswith(prefix) for prefix in INTERNAL)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate reach candidates from DCUs")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    wanted: dict[str, list[str]] = {}
    for class_name, (unit, variable) in OBJECTS.items():
        wanted.setdefault(unit, []).append(class_name)

    lines = [
        "# Generated by tools/gen_reach_candidates.py from the DCU symbol tables.",
        "# Every member of every class the reach unit has an object for, in four",
        "# forms; tools/reach_sweep.py drops what DCC 1.0 rejects.",
    ]
    types = {
        "gSweepForm": "TForm", "gSweepBox": "TScrollBox", "gSweepCanvas": "TCanvas",
        "gSweepPen": "TPen", "gSweepBrush": "TBrush", "gSweepFont": "TFont",
        "gSweepPicture": "TPicture", "gSweepIcon": "TIcon", "gSweepMeta": "TMetafile",
        "gSweepBitmap": "TBitmap", "gSweepGraphic": "TGraphic",
        "gSweepControl": "TControl", "gSweepWin": "TWinControl",
        "gSweepButton": "TButton", "gSweepPlayer": "TMediaPlayer",
        "gSweepList": "TListBox", "gSweepCombo": "TComboBox", "gSweepEdit": "TEdit",
        "gSweepLabel": "TLabel", "gSweepCheck": "TCheckBox",
        "gSweepRadio": "TRadioButton", "gSweepGroup": "TGroupBox",
        "gSweepMemo": "TMemo", "gSweepScroll": "TScrollBar",
        "gSweepStrings": "TStringList", "gSweepList2": "TList",
        "gSweepStream": "TStream", "gSweepComponent": "TComponent",
        "n2": "Integer", "s2": "string",
    }
    for name, type_name in types.items():
        lines.append(f"VAR: {name}: {type_name};")
    for name in types:
        if name not in ("n2", "s2"):
            lines.append(f"STMT: {name} := {types[name]}.Create(nil);")
    for class_name, (unit, variable) in OBJECTS.items():
        members = dcu_symbols.class_members(dcu_symbols.strings(LIB / f"{unit.upper()}.DCU"))
        if class_name not in members:
            continue
        for member in members[class_name]:
            if not is_public(member):
                continue
            for form in FORMS:
                lines.append("STMT: " + form.format(obj=variable, member=member))
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out} with {len(lines) - 3} candidates")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
