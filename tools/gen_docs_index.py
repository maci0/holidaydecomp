#!/usr/bin/env python3
"""Generate the knowledge-base unit map, check local links, and prepare a local Obsidian vault."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit

import gen_tree
import unit_names

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
UNIT_INDEX = DOCS / "units.md"
VAULT_APP = {"useMarkdownLinks": True, "newLinkFormat": "relative", "alwaysUpdateLinks": True,
             "newFileLocation": "folder", "newFileFolderPath": "docs", "attachmentFolderPath": "docs/assets"}


def render() -> str:
    lines = ["# Source unit map", "",
             "Generated by `tools/gen_docs_index.py` from the curated unit table in the source generator.",
             "Segment membership and form RTTI are evidence; filenames and subsystem labels remain reconstruction choices.",
             "[Current status](../STATUS.md) owns progress counts. [Native addressing](native-format.md#native-addresses) owns the address convention.", "",
             "| Segment | Tracked unit | Form classes | Working role |", "| ---: | --- | --- | --- |"]
    for segment, name, classes, evidence in gen_tree.generated_units():
        role = unit_names.JOBS[segment][1]
        owners = ", ".join(f"`{cls}`" for cls in classes) or "logic-only"
        lines.append(f"| {segment} | [{name}.PAS](../src/main/{name}.PAS) | {owners} | {role} |")
    lines += ["", "## Build support", "",
              "- [HOLIDAY.DPR](../src/main/HOLIDAY.DPR) creates the forms and starts the VCL application.",
              "- [REACH.PAS](../src/main/REACH.PAS) is synthetic library reachability support; it is not a recovered game unit.",
              "- [Form sources](../src/main/forms/README.md) own component layouts and callback wiring.",
              "- `DATAVAL.PAS`, `POOLS.PAS` and `TABLES.PAS` are local data outputs produced from your reference.",
              "", "See [source ownership](source-layout.md) before moving definitions or assigning original unit names.", ""]
    return "\n".join(lines)


def without_fences(text: str) -> str:
    return re.sub(r"(?ms)^```[^\n]*\n.*?^```[^\n]*(?:\n|$)", "", text)


def anchors(text: str) -> set[str]:
    result = set(re.findall(r'<a\s+id=[\"\x27]([^\"\x27]+)', text))
    counts = {}
    for title in re.findall(r"(?m)^#{1,6}\s+(.+?)\s*#*\s*$", without_fences(text)):
        title = re.sub(r"!?\[([^]]+)\]\([^)]*\)", r"\1", title)
        slug = re.sub(r"[^\w\s-]", "", title.lower()).replace(" ", "-")
        number = counts.get(slug, 0)
        counts[slug] = number + 1
        result.add(slug if number == 0 else f"{slug}-{number}")
    return result


def link_errors(path: Path, root: Path = ROOT) -> list[str]:
    errors = []
    for raw in re.findall(r"!?\[[^\]\n]*\]\(([^)\n]+)\)", without_fences(path.read_text())):
        target = urlsplit(raw.strip().strip("<>"))
        if target.scheme or target.netloc:
            continue
        destination = (path.parent / unquote(target.path)).resolve() if target.path else path.resolve()
        if not destination.is_relative_to(root.resolve()) or not destination.exists():
            errors.append(f"{path.relative_to(root)}: missing local link {raw}")
        elif target.fragment and destination.suffix == ".md" and unquote(target.fragment) not in anchors(destination.read_text()):
            errors.append(f"{path.relative_to(root)}: missing anchor {raw}")
    return errors


def document_paths() -> list[Path]:
    return [ROOT / "README.md", ROOT / "STATUS.md", ROOT / "layout/main/README.md",
            ROOT / "original/README.md", ROOT / "src/main/forms/README.md", *sorted(DOCS.rglob("*.md"))]


def init_vault(root: Path = ROOT) -> None:
    directory = root / ".obsidian"
    directory.mkdir(exist_ok=True)
    settings = {"app.json": VAULT_APP, "community-plugins.json": [],
                "templates.json": {"folder": "docs/templates", "dateFormat": "YYYY-MM-DD", "timeFormat": "HH:mm"}}
    for name, value in settings.items():
        path = directory / name
        if not path.exists():
            path.write_text(json.dumps(value, indent=2) + "\n")
    (root / "docs/assets").mkdir(parents=True, exist_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--init-vault", action="store_true")
    args = parser.parse_args()
    if args.init_vault:
        init_vault()
        print("Obsidian vault prepared at repository root; existing settings preserved")
    expected = render()
    if args.check:
        if not UNIT_INDEX.exists() or UNIT_INDEX.read_text() != expected:
            print("docs/units.md is stale; run make docs")
            return 1
    else:
        DOCS.mkdir(exist_ok=True)
        UNIT_INDEX.write_text(expected)
    errors = [error for path in document_paths() for error in link_errors(path)]
    if errors:
        print("\n".join(errors))
        return 1
    print(f"Knowledge base current: {len(document_paths())} Markdown pages; local links and anchors valid")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
