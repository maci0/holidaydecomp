#!/usr/bin/env python3
"""`docs/README.md`: the documentation corpus, indexed.

Twenty-one documents, 8000 lines, generated and hand-written mixed. A reader
arriving at this tree needs to know which file answers which question, and which
files are generated — those are the ones where a stale copy is a failed check
rather than a typo.

    python3 tools/gen_docs_index.py [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
INDEX = DOCS / "README.md"

# document -> the generator that owns it, where one does
GENERATED = {
    "globals.md": "tools/gen_globals.py",
    "strings.md": "tools/gen_strings.py",
    "units.md": "tools/gen_units.py",
    "forms.md": "tools/gen_forms.py",
    "media.md": "tools/gen_media.py",
    "records.md": "tools/gen_records.py",
    "status.md": "tools/gen_status.py",
    "roadmap.md": "tools/gen_roadmap.py",
    "worklist.csv": "tools/worklist.py",
}

SUMMARY = re.compile(r"^# (.+)$", re.M)


def rows() -> list[tuple[str, str, int, int, str]]:
    found = []
    for path in sorted(DOCS.glob("*.md")):
        if path.name == "README.md":
            continue
        text = path.read_text(encoding="utf-8")
        title = SUMMARY.search(text)
        found.append(
            (
                path.name,
                title.group(1) if title else path.stem,
                len(re.findall(r"^## ", text, re.M)),
                len(text.splitlines()),
                GENERATED.get(path.name, "—"),
            )
        )
    return found


def render() -> str:
    table = rows()
    lines = [
        "# The documentation",
        "",
        "This index is generated by `tools/gen_docs_index.py` from the files",
        "themselves. A document marked with a generator is compared against a fresh",
        "render by the test suite (`--check`), so a stale copy fails rather than",
        "misleads; the others are written by hand and checked by",
        "`tools/audit_docs.py`, which re-derives the sentence-level counts from the",
        "toolchain.",
        "",
        "| document | title | sections | lines | generated by |",
        "| --- | --- | ---: | ---: | --- |",
    ]
    for name, title, sections, size, generator in table:
        lines.append(f"| `{name}` | {title} | {sections} | {size} | `{generator}` |")
    lines += [
        "",
        f"**{len(table)} documents, {sum(row[3] for row in table)} lines, "
        f"{sum(row[2] for row in table)} sections.**",
        "",
        "## Which one to open",
        "",
        "* The objective and the measurements: `roadmap.md`.",
        "* What each unit is and what it calls: `units.md`.",
        "* Every data address and its readers: `globals.md`.",
        "* The object system — record, definition, element, tables: `object-model.md`.",
        "* The save game, the tick, the projections, the read-only globals:",
        "  `game-state.md`.",
        "* The maps and the layer projections: `map-layer.md`.",
        "* The screens, form by form: `screens.md` and `forms.md`.",
        "* The files, who reads and who writes them: `data-files.md` and `media.md`.",
        "* The compiler's idioms and the two disassembly traps: `codegen-patterns.md`.",
        "* The units' jobs, the reach work and the library gap: `segment-map.md`.",
    ]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate docs/README.md")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not INDEX.is_file() or INDEX.read_text(encoding="utf-8") != text:
            print("docs/README.md is stale; run python3 tools/gen_docs_index.py")
            return 1
        print("docs/README.md is current")
        return 0
    INDEX.write_text(text, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(ROOT)}: {len(text.splitlines())} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
