#!/usr/bin/env python3
"""Find which Delphi 1 API survives the compiler, one error at a time.

DCC 1.0 reports a single error per run, so probing the API by hand costs one
compile per mistake (round 93 spent twenty). This drives the same loop
mechanically: compile a unit full of candidate declarations and statements,
read the first error, drop that line, repeat — whatever compiles is the API
Delphi 1 actually accepts.

    python3 tools/reach_sweep.py tools/reach_candidates.txt --out build/reach_sweep

Candidate lines are prefixed `VAR:` (a declaration in the unit's var block) or
`STMT:` (a statement in the sweep procedure). A `#` line is a comment.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORK = ROOT / "src" / "main"
ERROR = re.compile(r"^RCHSWU\.PAS\((\d+)\): Error", re.M)

HEADER = """unit RCHSWU;
{ Generated by tools/reach_sweep.py: the candidates DCC 1.0 accepted. }
interface
procedure Sweep;
implementation
uses WinTypes, WinProcs, Forms, Graphics, StdCtrls, Buttons, Menus, ExtCtrls,
  Dialogs, Controls, Classes, SysUtils, MPlayer, FileCtrl;
var
"""

FOOTER = """
procedure Sweep;
begin
"""


def candidate_lines(path: Path) -> list[str]:
    lines = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("VAR:"):
            lines.append(("var", line[4:].strip()))
        elif line.startswith("STMT:"):
            lines.append(("stmt", line[5:].strip()))
        else:
            raise SystemExit(f"candidate line needs VAR: or STMT: — {line!r}")
    return lines


def write_unit(candidates: list[tuple[str, str]]) -> None:
    variables = [text for kind, text in candidates if kind == "var"]
    statements = [text for kind, text in candidates if kind == "stmt"]
    (WORK / "RCHSWU.PAS").write_text(
        HEADER + "\n".join(f"  {text}" for text in variables) + FOOTER
        + "\n".join(f"  {text}" for text in statements) + "\nend;\n\nend.\n",
        encoding="utf-8",
    )
    (WORK / "RCHSWP.DPR").write_text(
        "program RCHSWP;\nuses Forms, RCHSWU;\nbegin\n  Sweep;\nend.\n",
        encoding="utf-8",
    )


def compile_once() -> tuple[bool, str]:
    """Compile one candidate set.

    The sweep gets its **own** sandbox: each Rebrew invocation creates a fresh build directory, the
    same directory `./build.sh` uses, and a canonical build running at the same
    time removes it under the sweep (measured: `FileNotFoundError: build/dcc`).
    """
    # one sandbox per output file, so several sweeps can run at once
    sandbox = ROOT / "build" / f"dcc-{getattr(compile_once, 'tag', 'sweep')}"
    result = subprocess.run(
        [sys.executable, "-m", "rebrew.app.main", "build", "delphi", str(WORK / "RCHSWP.DPR"),
         "--output", str(ROOT / "build" / "rchswp.exe"),
         "--work-dir", str(sandbox)],
        capture_output=True, text=True, cwd=ROOT,
    )
    return result.returncode == 0, result.stdout + result.stderr


def main() -> int:
    parser = argparse.ArgumentParser(description="Sweep Delphi 1 API candidates")
    parser.add_argument("candidates", type=Path)
    parser.add_argument("--out", type=Path, default=ROOT / "tools" / "sweeps" / "reach_sweep.txt")
    parser.add_argument("--limit", type=int, default=4000)
    parser.add_argument("--sandbox-suffix", default="")
    args = parser.parse_args()

    # the sandbox and the temp unit names follow this run, so several sweeps can
    # be started at once (each DCC invocation owns its own sandbox)
    compile_once.tag = f"{args.out.stem}-{args.sandbox_suffix or 'a'}"
    kept = candidate_lines(args.candidates)
    dropped: list[tuple[str, str]] = []
    for _round in range(args.limit):
        write_unit(kept)
        ok, log = compile_once()
        if ok:
            break
        match = ERROR.search(log)
        if not match:
            print("compile failed without a line number:\n" + log[-2000:])
            return 1
        # the error's line number is 1-based inside the generated file; map it
        # back to the candidate by counting the var block and the body
        line_number = int(match.group(1))
        header_lines = HEADER.count("\n") + 1
        variables = [item for item in kept if item[0] == "var"]
        var_end = header_lines + len(variables)
        body_start = HEADER + "\n".join(f"  {t}" for _k, t in variables) + FOOTER
        body_first_line = body_start.count("\n") + 1
        if line_number <= var_end:
            index = line_number - header_lines
            kind = "var"
        else:
            index = len(variables) + (line_number - body_first_line)
            kind = "stmt"
        if not 0 <= index < len(kept):
            # An error the line mapping cannot reach: losing the last `var`
            # declaration makes the block empty and DCC points at line 1. Drop
            # the last declaration and go on; when none is left, stop and keep
            # the survivors rather than wasting the run.
            remaining = [i for i, item in enumerate(kept) if item[0] == "var"]
            if remaining:
                dropped.append(kept.pop(remaining[-1]))
                print(f"dropped (var): {dropped[-1][1][:70]} — line {line_number} unmappable")
                continue
            print(f"could not map line {line_number}; keeping what survived")
            break
        dropped.append(kept.pop(index))
        print(f"dropped ({kind}): {dropped[-1][1][:70]}  — {log.strip().splitlines()[-1][:80]}")
    else:
        print("hit the round limit — the kept set is NOT verified")

    # verify before writing — but never lose a run's survivors to a failed
    # verification: write them anyway, mark the file, and say so. (Three parts of
    # the broad sweep were lost to the earlier behaviour, which returned before
    # writing anything.)
    write_unit(kept)
    ok, log = compile_once()
    verified = ok
    if not ok:
        print("the kept set does not compile; writing it unverified anyway")

    header = "" if verified else "# UNVERIFIED: the kept set did not compile\n"
    args.out.write_text(
        header + "\n".join(f"{kind.upper()}: {text}" for kind, text in kept) + "\n",
        encoding="utf-8",
    )
    (args.out.with_suffix(args.out.suffix + ".dropped")).write_text(
        "\n".join(f"{kind.upper()}: {text}" for kind, text in dropped) + "\n",
        encoding="utf-8",
    )
    print(f"kept {len(kept)} candidates, dropped {len(dropped)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
