#!/usr/bin/env python3
"""`docs/records.md`: the field layout of every record the game reads or writes.

The RTL's `BlockRead`/`BlockWrite` (`33:0x0CB7`/`33:0x0CBE`) are how this game
moves its files, one field at a time, so the sequence of `add di, +0xNNN` and
`push <width>` in front of each call *is* the record's layout. Writers and
readers come out as pairs with identical lists, which is the check that the
extraction is right. Sizes quote the reviewed inventory, so a corrected
extent or a folded head prints its reviewed value rather than discovery's.
Generated by `tools/gen_records.py`; check with `--check`.
"""

from __future__ import annotations

import argparse
import collections
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import decompile  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "records.md"
READ = "0xcb7"
WRITE = "0xcbe"
MIN_FIELDS = 3  # record-moving calls in one procedure


def fields(segment, offset: int, size: int) -> list[tuple[int | None, int | None]]:
    """(field offset, byte count) for every record-moving call in one procedure.

    The offset comes from an `add di, +0xNNN` in front of the call; the count is
    the last constant pushed before it, restricted to a plausible record size
    (a larger constant is a far pointer or a jump target, not a length).
    """
    insns = list(decompile.engine().disasm(segment.data[offset : offset + size], offset))
    out: list[tuple[int | None, int | None]] = []
    for index, ins in enumerate(insns):
        if ins.mnemonic != "lcall":
            continue
        if not (ins.op_str.endswith(READ) or ins.op_str.endswith(WRITE)):
            continue
        window = [
            f"{earlier.mnemonic} {earlier.op_str}"
            for earlier in insns[max(0, index - 8) : index]
        ]
        field = next(
            (
                match.group(1)
                for text in window
                for match in [re.search(r"add di, (0x[0-9a-f]+)", text)]
                if match
            ),
            None,
        )
        count = next(
            (
                int(match.group(1), 0)
                for text in reversed(window)
                for match in [re.fullmatch(r"push (\d+|0x[0-9a-f]+)", text)]
                if match and 0 < int(match.group(1), 0) <= 0x800
            ),
            None,
        )
        out.append((int(field, 16) if field else None, count))
    return out


def describes(layout: list[tuple[int | None, int | None]]) -> str:
    """What kind of record I/O this call list is.

    Two shapes share the same RTL entry points: a **field layout** (one call per
    field, each with `add di, +0xNNN` in front) and a **whole-record move** (one
    call whose count is the record's size, e.g. `push 0x2c` for 44-byte nodes).
    Counting the explicit offsets is what tells them apart, and the second shape
    is where the record sizes come from.
    """
    explicit = [field for field, _count in layout if field is not None]
    counts = [count for _field, count in layout if count]
    if len(explicit) >= 2:
        return f"field layout, {sum(counts)} bytes"
    if counts:
        return "whole record(s): " + ", ".join(f"{count} bytes" for count in sorted(set(counts)))
    return "counts from variables"


def collect() -> dict[tuple[int, int, int], tuple[str, list[tuple[int | None, int | None]]]]:
    image = decompile.Image(decompile.ORIGINAL)
    classes = decompile.form_classes_by_segment(image)
    found: dict[tuple[int, int, int], tuple[str, list]] = {}
    for segment in image.program_segments():
        for function in decompile.discover(segment, classes.get(segment.index, [])):
            insns = decompile.procedure_body(segment, function)
            kinds = [
                ins.op_str[-4:]
                for ins in insns
                if ins.mnemonic == "lcall"
                and (ins.op_str.endswith(READ) or ins.op_str.endswith(WRITE))
            ]
            if not kinds:
                continue
            layout = fields(segment, function.offset, function.size)
            # the offset is explicit only when the code reloads `di`; an
            # incrementally advanced writer has none, but its widths are still
            # the layout, so the call count is what qualifies a procedure
            if len(layout) < MIN_FIELDS:
                continue
            kind = "write" if kinds.count("0xcbe") >= kinds.count("0xcb7") else "read"
            found[(segment.index, function.offset, function.size)] = (kind, layout)
    return found


def callers() -> tuple[dict[tuple[int, int], list[tuple[int, int]]], dict[int, list[tuple[int, int]]]]:
    """segment:offset -> the procedures that call into it, by scanning `lcall`.

    The far-call census resolves *which segment* a call reaches but not which
    procedure, so the call sites are found here. A call to another segment
    carries a relocation placeholder (`lcall 0xffff, 0x4e34`) rather than the
    segment number, so those are attributed by offset alone; a same-segment call
    is a near `call`. The second map is the offset-only one.
    """
    image = decompile.Image(decompile.ORIGINAL)
    classes = decompile.form_classes_by_segment(image)
    found: dict[tuple[int, int], list[tuple[int, int]]] = {}
    by_offset: dict[int, list[tuple[int, int]]] = {}
    for segment in image.program_segments():
        for function in decompile.discover(segment, classes.get(segment.index, [])):
            for ins in decompile.procedure_body(segment, function):
                if ins.mnemonic == "lcall":
                    match = re.fullmatch(r"(0x[0-9a-f]+), (0x[0-9a-f]+)", ins.op_str)
                    if not match:
                        continue
                    target_segment = int(match.group(1), 16)
                    target_offset = int(match.group(2), 16)
                    if target_segment > 0xFF:  # a relocation placeholder
                        by_offset.setdefault(target_offset, []).append(
                            (segment.index, function.offset)
                        )
                        continue
                    key = (target_segment, target_offset)
                elif ins.mnemonic == "call":
                    # a procedure in the same segment is called with a near call
                    near = re.fullmatch(r"(0x[0-9a-f]+)", ins.op_str)
                    if not near:
                        continue
                    key = (segment.index, int(near.group(1), 16))
                else:
                    continue
                found.setdefault(key, []).append((segment.index, function.offset))
    return found, by_offset


def render() -> str:
    found = collect()
    inventory_sizes = {
        int(row["va"]): int(row["size"])
        for row in json.loads(
            (ROOT / "src" / "main" / "function_structure.json").read_text(encoding="utf-8")
        )
    }
    callers_of, callers_by_offset = callers()
    by_layout: dict[tuple, list[tuple[int, int, int]]] = collections.defaultdict(list)
    for key, (_kind, layout) in found.items():
        by_layout[tuple(layout)].append(key)
    lines = [
        "# The game's record layouts",
        "",
        "Every procedure that moves a record with the RTL's `BlockRead`/`BlockWrite`,",
        "with the field offsets and widths taken from the code in front of each call.",
        "A writer and its reader come out as a pair here, which is the check that the",
        "extraction is right: their lists must be identical. `—` marks a field whose",
        "address the code advances instead of reloading, so only its width is known;",
        "the width sequence is still the record's layout.",
        "",
        f"**{len(found)} procedures, {len(by_layout)} distinct layouts.**",
        "",
    ]
    for layout, keys in sorted(
        by_layout.items(),
        key=lambda item: (-len(item[1]), tuple(f if f is not None else -1 for f, _c in item[0])),
    ):
        kinds = {found[key][0] for key in keys}
        lines += [
            f"## {' and '.join(sorted(kinds))} — {len(keys)} procedure(s), "
            f"{len(layout)} calls, {describes(layout)}",
            "",
        ]
        for segment, offset, size in sorted(keys):
            called_by = callers_of.get((segment, offset)) or callers_by_offset.get(
                offset, []
            )
            where = (
                ", ".join(f"`{caller_segment}:{caller_offset:#06x}`"
                          for caller_segment, caller_offset in sorted(set(called_by))[:4])
                or "no direct caller found"
            )
            reviewed = inventory_sizes.get(segment * 0x10000 + offset, size)
            lines.append(f"* `{segment}:{offset:#06x}` ({reviewed} bytes), called by {where}")
        lines += ["", "| field | bytes |", "| ---: | ---: |"]
        for field, count in layout:
            shown = f"`+{field:#05x}`" if field is not None else "—"
            lines.append(f"| {shown} | {count} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate docs/records.md")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not DOC.is_file() or DOC.read_text(encoding="utf-8") != text:
            print("docs/records.md is stale; run python3 tools/gen_records.py")
            return 1
        print("docs/records.md is current")
        return 0
    DOC.write_text(text, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
