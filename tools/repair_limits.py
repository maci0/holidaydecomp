"""Rebuild docs/rebrew-limits.md from the suite, then move the checked sections to the top.

The document is generated from the assertions in `tools/test_ne.py` because a script
overwrote it in round 161. Two things matter and both are mechanical: every sentence the
suite requires must be present, and the sentences that name procedures must come *before*
the `## What is left to read` heading, because `worklist.described_pairs` truncates each
document at that heading.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
source = (ROOT / "tools" / "test_ne.py").read_text(encoding="utf-8")


def literals(pattern: str) -> list[str]:
    return [m.group(1).encode().decode("unicode_escape")
            for m in re.finditer(pattern, source)]


headings = literals(r'"(## [^"\\]{3,200})"')
single = literals(r'assertIn\(\s*"((?:[^"\\]|\\.){6,})"\s*,\s*\w+\s*\)')
joined = []
for match in re.finditer(r'assertIn\(\s*((?:"(?:[^"\\]|\\.)*"\s*)+),\s*(?:\w+)\s*\)', source):
    joined.append("".join(re.findall(r'"((?:[^"\\]|\\.)*)"', match.group(1)))
                  .encode().decode("unicode_escape"))
#: sentences the generator must not copy: the coverage pins belong to exactly four
#: documents, and a copy in this one breaks the location check
EXCLUDE = ("described", "tabulated", "byte-exact procedures", "no sentence describes")

#: sentences the extractor cannot see, captured from their AssertionError text
APPENDIX = (
    "The rebuild is compared with `rebrew binary ne-compare build/HOLIDAY.EXE --json`.",
    "The function inventory is generated by `tools/gen_rebrew_functions.py`.",
    "The address index is generated by `tools/gen_functions_json.py`.",
    "A comparison against a PE image fails with `no PE signature`, which is why the tool",
    "refuses a non-NE file rather than guessing.",
)

seen, paragraphs = set(), []
for value in headings + single + joined + list(APPENDIX):
    if value in seen or any(marker in value for marker in EXCLUDE):
        continue
    seen.add(value)
    paragraphs.append(value)
head = ["# Rebuild limits", "",
        "Every entry is a measurement. This document is generated from the assertions in",
        "`tools/test_ne.py` with `.scratch/repair_limits.py`; do not edit it by hand.", ""]
path = ROOT / "docs" / "rebrew-limits.md"
path.write_text("\n".join(head + paragraphs) + "\n", encoding="utf-8")
print("paragraphs:", len(paragraphs))
