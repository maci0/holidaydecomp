        "table; a dispatch needs its **handler table**; a 32-bit arithmetic routine",
        "needs its units and its rounding. The shape is the first thing to know and",
        "the last thing a byte count tells you.",
        "",
        "The last column is the strongest loop evidence in the profile — a helper",
        "called the same number of times as the parameter with the most uses is a",
        "loop, which is how round 225 read two procedures. `2:0x000E` calls `0x08EF`",
        "**46 times**, `11:0x3CFD` calls `0x0666` 17, and `22:0x1C54` walks at the map",
        "stride `0xFB` eight times. A procedure with a repetition count can be read",
        "from the loop body outward.",
        "",
        "## The twenty-four largest described procedures",
        "",
