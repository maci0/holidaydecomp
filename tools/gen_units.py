"""`docs/units.md`: one dossier per program unit, from the measurements.

Each section gathers what the reversal established about a unit in one place —
its size, the literals it passes, the globals only it touches, the units that
call it and that it calls — so the reconstructed tree can be read unit by unit
instead of round by round. Generated by `tools/gen_units.py`; the one-line job is
a table here, everything else is measured.
"""

