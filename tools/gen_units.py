ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "units.md"

# Segment -> (unit file, one-line job). The jobs are the findings of the
# reversal, one line each; `docs/segment-map.md` carries the evidence.
JOBS: dict[int, tuple[str, str]] = unit_names.JOBS


def near_far_split(image, segment: int, functions) -> tuple[int, int]:
    """How many of the segment's procedures end in `ret` (near) or `retf` (far).

    In Delphi 1 a unit's procedures are **far** by default; only procedures declared in
    the unit's *implementation* section are near, because nothing outside can call them.
    A `ret N` ending therefore says the procedure was **private to its unit**, and
    `retf N` says the unit exported it (round 401, found by matching `22:0x4786`). Only
    procedures that end in a return are counted: `discover()` also reports interior
    entry points, which have no return of their own.
    """
    near = far = 0
    for function in functions:
        returns = [i for i in decompile.procedure_body(image.segments[segment], function)
                   if i.mnemonic in ("ret", "retf")]
        if not returns:
            continue
        if returns[-1].mnemonic == "ret":
            near += 1
        else:
            far += 1
    return near, far


def near_far_line(image, segment: int, functions) -> str:
    near, far = near_far_split(image, segment, functions)
    total = near + far
    if not total:
        return "* Procedure endings: none found."
    return (f"* Procedure endings: **{near} near** (private to the unit) and "
            f"**{far} far** (exported) of {total} that end in a return.")


def sections(image) -> list[str]:
    classes = decompile.form_classes_by_segment(image)
    functions = {
        segment.index: decompile.discover(segment, classes.get(segment.index, []))
        for segment in image.program_segments()
    }
    census, _dropped = decompile.datamap(image)
    strings = gen_strings.literals(image)
    census_calls, _indirect = decompile.far_calls(image)
    resolved = decompile.resolved_targets(image, census_calls)
    callers: dict[int, set[int]] = collections.defaultdict(set)
    callees: dict[int, set[int]] = collections.defaultdict(set)
    for offset, entry in census_calls.items():
        target = resolved.get(offset)
        if target is None:
            continue
        for caller in entry["callers"]:
            callers[target].add(caller)
            callees[caller].add(target)
    literals_by_segment: dict[int, set[str]] = collections.defaultdict(set)
    for text, owners in strings.items():
        for segment, _offset in owners:
            literals_by_segment[segment].add(text)
    own_globals: dict[int, list[int]] = collections.defaultdict(list)
    for address, entry in census.items():
        # every bare bracketed address is DGROUP — there is no floor to apply, and
        # the old `address < 0x2D79` test threw away the initialised part of the
        # segment (`[0x7C]`, read 290 times, among 61 addresses)
        if len(entry["segments"]) == 1:
            own_globals[next(iter(entry["segments"]))].append(address)
    media = gen_media.inventory(image)
    tables_by_segment: dict[int, list[dict]] = collections.defaultdict(list)
    for table in decompile.jump_tables(image):
        tables_by_segment[table["segment"]].append(table)
    reads_of = globals_census_by_unit(image)
    sounds = decompile.sound_commands(image)
    # the program-wide ranking is generated here so no hand-written section can
    # state a partial one (rounds 162 and 172 both did, from different subsets)
    inventory_sizes = {
        int(row["va"]): int(row["size"])
        for row in json.loads(
            (ROOT / "src" / "main" / "function_structure.json")
            .read_text(encoding="utf-8")
        )
    }

    def size_of(index: int, function) -> int:
        """The reviewed inventory's size, discovery's for a folded tail."""
        return inventory_sizes.get(index * 0x10000 + function.offset, function.size)

    every = [
        (index, function)
        for index, functions_of in functions.items()
        for function in functions_of
    ]
    largest = sorted(every, key=lambda item: -size_of(item[0], item[1]))[:20]
    # the near/far split is a source-structure signal: a `ret N` ending means the
    # procedure was private to its unit, `retf N` that the unit exported it
    endings = [
        "## What the return instructions say about each unit's interface",
        "",
        "In Delphi 1 a unit's procedures are **far** by default: only procedures declared in",
        "the unit's *implementation* section are **near**, because nothing outside can call",
        "them. A procedure that ends in `ret N` was therefore private to its unit, and one",
        "that ends in `retf N` was exported (round 401, found by matching `22:0x4786`).",
        "Only procedures that end in a return are counted — `discover()` also reports",
        "interior entry points, which have none.",
        "",
        "| unit | near (private) | far (exported) |",
        "| --- | ---: | ---: |",
    ]
    near_total = far_total = 0
    for index in range(25):
        near, far = near_far_split(image, index, functions.get(index, []))
        near_total += near
        far_total += far
        name = JOBS[index][0].removesuffix(".PAS") if index in JOBS else str(index)
        endings.append(f"| `{name}` | {near} | {far} |")
    endings += [
        f"| **program** | **{near_total}** | **{far_total}** |",
        "",
        f"**Most procedures are far**: {far_total} end `retf` against {near_total} that end",
        "`ret`. The whole-instruction epilogue matcher is the default, so a `retf imm16`",
        "counts. A procedure that ends `ret` cannot be called from another segment, so the",
        "near/far bit is the only evidence in the image for where a unit's interface ended.",
        "",
        "> **A defect sits under this table, measured in round 405.** Of the 1306 discovered",
        "> procedures, **916 report no return at all** — and they are not bodyless: they are the",
        "> ones whose last instruction is `retf imm16`. `decompile.EPILOGUE_RE` matches",
        "> `leave; retf imm16` as its first two bytes, so the discovered range ends two bytes",
        "> before the return, the truncated final instruction drops out and the procedure looks",
        "> as if it never returned. Matching the whole instruction gives **1029 far, 254 near and",
        "> 23 with no return**, so the honest reading is the opposite of the one above: the",
        "> program's procedures are overwhelmingly *exported*, and the near ones are the",
        "> exceptions. The fix is not applied yet because it moves ~170 pinned measurements and",
        "> six measurement caches, none of which has a generator; it lands with that tool.",
    ]
    ranking = [
        "## The twenty largest procedures in the program",
        "",
        "Measured over all twenty-five units at once, because two hand-written",
        "rankings in `docs/segment-map.md` were assembled from subsets and both were",
        "wrong (rounds 162 and 172).",
        "",
        "| # | procedure | unit | bytes |",
        "| ---: | --- | --- | ---: |",
    ]
    for position, (index, function) in enumerate(largest, 1):
        ranking.append(
            f"| {position} | `{index}:{function.offset:#06x}` | "
            f"`{JOBS.get(index, ('?', ''))[0]}` | {size_of(index, function)} |"
        )
    ranking.append("")
    function_spans_for_tables = [
        (index, function.offset, function.end)
        for index, segment in enumerate(image.segments)
        if index <= 24
        for function in decompile.discover(
            segment, decompile.form_classes_by_segment(image).get(index, [])
        )
    ]
    every_table = [
        table for tables in tables_by_segment.values() for table in tables
    ]
    full = [table for table in every_table if table["count"] == table["handlers"]]
    shared = [table for table in every_table if table["count"] != table["handlers"]]
    largest_tables = sorted(every_table, key=lambda table: -table["count"])[:5]
    ranking += [
        "## The dispatch tables",
        "",
        f"`decompile.jump_tables()` finds **{len(every_table)} `jmp word ptr cs:[bx + T]`"
        f" tables** in the program: **{len(full)}** give every entry its own handler and"
        f" **{len(shared)}** share handlers between entries. The busiest unit is segment"
        f" 17 with {len(tables_by_segment[17])} tables; segments 20, 18 and 23 have"
        f" {len(tables_by_segment[20])}, {len(tables_by_segment[18])} and"
        f" {len(tables_by_segment[23])}.",
        "",
        "| table | entries | handlers |",
        "| --- | ---: | ---: |",
    ]
    for table in largest_tables:
        ranking.append(
            f"| `{table['segment']}:{table['table']:#06x}` | {table['count']} | "
            f"{table['handlers']} |"
        )
    ranking.append("")
    ranking.append(
        "The three shapes are worth telling apart: a full table is a `case` with one"
        " arm per value, a table with few handlers is a `case` whose values fall into"
        " groups, and the extreme — `17:0x3428` and `17:0x399F` with **55 entries and"
        " two handlers each** — is a two-way test written as a jump table."
    )
    ranking.append("")
    distinct = [table for table in every_table if table["handlers"] == table["count"]]
    grouped = [table for table in every_table if table["handlers"] < table["count"]]
    biggest_command = sorted(distinct, key=lambda t: -t["count"])[:4]
    most_shared = sorted(grouped, key=lambda t: (t["handlers"] / t["count"], -t["count"]))[:4]
    ranking += [
        f"Read the other way, the split is **{len(distinct)} command tables against"
        f" {len(grouped)} state tables**: in {len(distinct)} of the 62 every entry has"
        " its own handler, which is what a `case` over command bytes looks like, and in"
        f" the other {len(grouped)} at least two entries share one, which is what a"
        " state machine or a grouped decision looks like. The largest command tables"
        " are "
        + ", ".join(
            f"`{table['segment']}:{table['table']:#06x}` ({table['count']})"
            for table in biggest_command
        )
        + ", and the most shared are "
        + ", ".join(
            f"`{table['segment']}:{table['table']:#06x}` ({table['count']} entries,"
            f" {table['handlers']})"
            for table in most_shared
        )
        + ".",
        "",
        "That classification is a property of the *compiler's* output rather than of"
        " the source: an all-distinct table means the source had no shared arms, so"
        " the shape tells a reader where a command vocabulary lives without reading"
        " any handler.",
        "",
        "Those command vocabularies have owners, and naming them is what turns the"
        " row above into a worklist. Each all-distinct table, its jump site and the",
        "procedure that contains it:",
        "",
        "| procedure | table | commands |",
        "| --- | ---: | ---: |",
    ]
    for table in sorted(distinct, key=lambda t: -t["count"])[:12]:
        owner = None
        for (index, start, end) in function_spans_for_tables:
            if index == table["segment"] and start <= (table.get("site") or -1) < end:
                owner = start
                break
        ranking.append(
            f"| `{table['segment']}:{owner:#06x}` | `{table['table']:#06x}` | "
            f"{table['count']} |"
            if owner is not None
            else f"| — | `{table['table']:#06x}` | {table['count']} |"
        )
    ranking.append("")
    # a worklist with reasons: the largest procedures no document mentions yet,
    # each classified by the profile a reader can reproduce in one command
    import profile_proc

    # "Left to read" means **no sentence describes it**, not "no document mentions
    # it": 1306 of 1306 procedure addresses appear somewhere, 380 of them only in
    # `docs/segment-map.md`'s dumps, so the weaker test reports 0 and hides the work.
    # `docs/worklist.csv` keeps the weaker flag, because a reader searching for an
    # address wants it; this section wants the stricter one.
    described = __import__("worklist").described_pairs()
    unread = sorted(
        (
            (size_of(index, function), index, function.offset)
            for index, segment in enumerate(image.segments)
            if index <= 24
            for function in decompile.discover(
                segment, decompile.form_classes_by_segment(image).get(index, [])
            )
            if (index, function.offset) not in described
        ),
        reverse=True,
    )
    described_largest = []
    for index, segment in enumerate(image.segments):
        if index > 24:
            continue
        unit_name = unit_names.JOBS.get(index, (f"SEG{index}", ""))[0]
        for function in decompile.discover(
            segment, decompile.form_classes_by_segment(image).get(index, [])
        ):
            if (index, function.offset) in described:
                described_largest.append((index, function.offset, function, unit_name))
    described_largest.sort(key=lambda item: -size_of(item[0], item[2]))
    described_largest = described_largest[:24]
    shapes: collections.Counter = collections.Counter()
    unread_rows = []
    for size, index, offset in unread[:40]:
        result = profile_proc.profile(image, index, offset)
        if not result:
            continue
        if result["locals"] == 0 and not result["globals"]:
            shape = "pass-through"
        elif result["helpers"]["lmul"] + result["helpers"]["ldiv"] >= 6:
            shape = "32-bit arithmetic"
        elif result["tables"]:
            shape = "dispatch"
        elif result["strides"]:
            shape = "array walk"
        elif result["indirect"]:
            shape = "vtable driver"
        else:
            shape = "mixed"
        shapes[shape] += 1
        if len(unread_rows) < 12:
            unread_rows.append(
                f"| `{index}:{offset:#06x}` | {size} | {result['instructions']} | "
                f"{shape} | {len(result['parameters'])} | {result['locals']} | "
                f"{profile_proc.loop_signature(result)} |"
            )
