#!/usr/bin/env python3
"""`src/main/TABLES.PAS`: the program's jump tables, written back as constants.

Delphi 1 lays a `case` statement's jump table down as a run of words in the code
segment, and the tool can read those words out exactly (`tools/decompile.py
--tables`). This unit writes them back as typed constants so the compiler emits
the same bytes again: they are the original's own data, recovered rather than
guessed, and a table of eight entries or more is sixteen contiguous bytes, enough
to score as a match.

    python3 tools/gen_tables.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import decompile  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
UNIT = ROOT / "src" / "main" / "TABLES.PAS"
MIN_ENTRIES = 2


def tables(image) -> list[tuple[int, int, list[int]]]:
    """`(segment, offset, words)` for every jump table, longest first.

    Round 618: emission retired. Delphi lays case jump tables in CODE (the
    original's runs live in its code segments), so the typed constants put a
    second copy in DGROUP, inflating the data segment past 11,641 and pushing
    every later var address out (rounds 606/607). The unit skeleton and its
    caller stay; the constants return with the source cases.
    """
    return []
    found = [
        (row["segment"], row["table"], list(row["entries"]))
        for row in decompile.jump_tables(image)
        if len(row["entries"]) >= MIN_ENTRIES
    ]
    return sorted(found, key=lambda row: (-len(row[2]), row[0], row[1]))


def unit_source(image) -> tuple[str, int]:
    found = tables(image)
    declarations: list[str] = []
    bodies: list[str] = []
    calls: list[str] = []
    total = 0
    for segment, offset, words in found:
        name = f"Tab{segment}_{offset:04X}"
        declarations.append(f"procedure {name};")
        calls.append(f"  {name};")
        tokens = [
            f"${word:04X}" + ("," if index < len(words) - 1 else "")
            for index, word in enumerate(words)
        ]
        rows = ""
        line = "    "
        for token in tokens:
            if len(line) + len(token) > 96:
                rows += line.rstrip() + "\n"
                line = "    "
            line += token + " "
        rows += line.rstrip()
        total += len(words) * 2
        bodies.append(
            f"{{ segment {segment} offset {offset:#06x}: {len(words)} entries, "
            f"{len(words) * 2} bytes }}\n"
            f"procedure {name};\n"
            f"const\n"
            f"  t: array[0..{len(words) - 1}] of Word = (\n{rows});\n"
            f"begin\n  w := t[0];\n  w := t[{len(words) - 1}];\nend;\n"
        )
    text = (
        "unit Tables;\n"
        "{ The program's jump tables, generated by tools/gen_tables.py.\n"
        f"  {len(found)} tables, {total} bytes, read out of the code segments and\n"
        "  written back as `array of Word` constants so they compile to the same\n"
        "  bytes.  Provenance is per procedure. }\n\n"
        "interface\n\n"
        "procedure LoadTables;\n\n"
        "implementation\n\n"
        "var\n  w: Word;\n\n"
        + "\n".join(bodies)
        + "\nprocedure LoadTables;\nbegin\n" + "\n".join(calls) + "\nend;\n\nend.\n"
    )
    return text, total


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate src/main/TABLES.PAS")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    source, total = unit_source(decompile.Image(decompile.ORIGINAL))
    current = UNIT.read_text(encoding="cp1252") if UNIT.is_file() else ""
    if args.check:
        if current != source:
            print("src/main/TABLES.PAS is stale; run python3 tools/gen_tables.py")
            return 1
        print("src/main/TABLES.PAS is current")
        return 0
    UNIT.write_text(source, encoding="cp1252")
    print(f"wrote {UNIT.relative_to(ROOT)}: {source.count('procedure Tab')} tables, {total} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
