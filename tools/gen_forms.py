#!/usr/bin/env python3
"""`docs/forms.md`: one entry per recovered form, from the streams and the code.

A form is the one thing this reconstruction has from both ends: the `.DFM` stream
says what the designer put on it, and the unit's segment says what the code does
with the strings it passes. Generated by `tools/gen_forms.py`; check with
`--check` (the suite does).
"""

from __future__ import annotations

import argparse
import collections
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import decompile  # noqa: E402
import gen_strings  # noqa: E402
import gen_tree  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "forms.md"
FORMS_DIR = ROOT / "src" / "main" / "forms"


def form_units() -> dict[str, tuple[Path, int]]:
    """class name -> (unit file, segment index), from the reconstructed tree."""
    # a generated unit declares *all* the form classes of its segment since round
    # 463, so the mapping is one class to its segment's unit file, not one class
    # to a file of its own
    units: dict[str, tuple[Path, int]] = {}
    for index, name, classes, _evidence in gen_tree.generated_units():
        path = ROOT / "src" / "main" / f"{name}.PAS"
        for class_name in classes:
            units.setdefault(class_name, (path, index))
    return units


def render() -> str:
    image = decompile.Image(decompile.ORIGINAL)
    strings = gen_strings.literals(image)
    literals_by_segment: dict[int, set[str]] = collections.defaultdict(set)
    for text, owners in strings.items():
        for segment, _offset in owners:
            literals_by_segment[segment].add(text)
    units = form_units()
    # which units each form's segment calls, from the call graph
    census, _indirect = decompile.far_calls(image)
    resolved = decompile.resolved_targets(image, census)
    calls_by_caller: dict[int, set[int]] = collections.defaultdict(set)
    for offset, entry in census.items():
        target = resolved.get(offset)
        if target is None:
            continue
        for caller in entry["callers"]:
            calls_by_caller[caller].add(target)
    # the sound commands each unit issues, through segment 20's entry
    sounds_by_unit: dict[int, set[int]] = collections.defaultdict(set)
    for segment in image.program_segments():
        for function in decompile.discover(
            segment, decompile.form_classes_by_segment(image).get(segment.index, [])
        ):
            body = decompile.procedure_body(segment, function)
            for index, ins in enumerate(body):
                call = re.fullmatch(r"(0x[0-9a-f]+), 0x30b6", ins.op_str)
                if ins.mnemonic != "lcall" or not call:
                    continue
                target = int(call.group(1), 16)
                previous = body[index - 1]
                pushed = re.fullmatch(
                    r"push (\d+|0x[0-9a-f]+)", f"{previous.mnemonic} {previous.op_str}"
                )
                if not pushed:
                    continue
                command = int(pushed.group(1), 0)
                # the offset alone is ambiguous; `0x30B6` exists in many segments,
                # so accept only segment 20 or a relocation placeholder with a
                # command number the sound table actually has (1..42)
                if target == 20 or (target > 0xFF and 1 <= command <= 42):
                    sounds_by_unit[segment.index].add(command)
    lines = [
        "# The forms, one entry each",
        "",
        "Every recovered form, with what the designer put on it (the `.DFM` stream)",
        "and what its code passes as strings (the segment's literals). The browser",
        "for the screens themselves is `docs/screens.md`; this is the inventory.",
        "",
        f"**{len(units)} forms.**",
        "",
    ]
    for stream in sorted(FORMS_DIR.glob("*.DFM")):
        text = stream.read_text(encoding="cp1252", errors="replace")
        top = re.search(r"^object (\w+): (\w+)", text, re.M)
        if not top:
            continue
        class_name = top.group(2)
        unit, index = units.get(class_name, (None, None))
        components = re.findall(r"^\s*object (\w+): (\w+)", text, re.M)[1:]
        handlers = re.findall(r"^\s+(On\w+) = (\w+)", text, re.M)
        literals = sorted(literals_by_segment.get(index, set()))
        assets: dict[str, list[str]] = collections.defaultdict(list)
        for literal in literals:
            if "." in literal:
                assets[literal.rsplit(".", 1)[1].lower()].append(literal)
        lines += [
            f"## `{class_name}` — {top.group(1)}",
            "",
            f"* unit `{unit.name if unit else '?'}`, code segment {index}.",
            f"* **{len(components)} components**: "
            + ", ".join(f"`{name}` ({kind})" for name, kind in components),
            f"* **{len(handlers)} wired handlers**: "
            + ", ".join(f"`{event}` -> `{method}`" for event, method in handlers),
            "* sound commands: "
            + (
                ", ".join(str(command) for command in sorted(sounds_by_unit.get(index, set())))
                or "none"
            )
            + ".",
            "* calls units: "
            + (
                ", ".join(str(target) for target in sorted(calls_by_caller.get(index, set())))
                or "nobody"
            )
            + ".",
            f"* **{len(literals)} literals** in its segment"
            + (
                ": "
                + "; ".join(
                    f"{kind} ({len(names)})" for kind, names in sorted(assets.items())
                )
                if assets
                else ""
            )
            + ".",
            "",
        ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate docs/forms.md")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not DOC.is_file() or DOC.read_text(encoding="utf-8") != text:
            print("docs/forms.md is stale; run python3 tools/gen_forms.py")
            return 1
        print("docs/forms.md is current")
        return 0
    DOC.write_text(text, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
